"""EU AI Act Art. 50 runtime transparency: disclosure, machine-readable marking and verification.

What this really provides
* ``required_measures(profile)``: which Art. 50 measures apply to a system profile (no guessing: unknown => stated).
* Interaction disclosure text for AI systems that talk to people (Art. 50(1)).
* A signed provenance manifest (HMAC-SHA256, versioned) bound to the SHA-256 of the exact content, for text and
  arbitrary bytes, and real embedded metadata for PNG images (``tEXt`` chunk). ``verify`` detects any content or
  manifest change (Art. 50(2) machine-readable marking).
* Visible labels for deepfakes (Art. 50(4)) and AI-generated public-interest text (Art. 50(4) second paragraph).
* ``release`` is fail-closed: if a required measure cannot be applied the output is NOT released.

Honest limits (reported by ``LIMITATIONS``): metadata/sidecar marking is removable and is not a robust
watermark; this is not C2PA; detection of unmarked third-party content is out of scope; whether an exception
(assistive editing, human editorial responsibility, law-enforcement use) applies is a legal determination
that must be recorded in the profile by a person.
"""
from __future__ import annotations

import base64
import hashlib
import hmac
import json
import struct
import time
import zlib
from dataclasses import dataclass, field
from typing import Any, Dict, List, Mapping, Optional, Tuple

from .risk_classification import AISystemProfile

MANIFEST_VERSION = "slai.ai-provenance.v1"
PNG_KEYWORD = "slai:ai-provenance"
LIMITATIONS = (
    "Marking is metadata/sidecar based and can be stripped; it is not a robust watermark.",
    "Not a C2PA implementation.",
    "Exceptions (assistive editing, editorial responsibility, law enforcement) are legal determinations recorded by a person.",
    "Art. 50 dates: verify against the consolidated text (see eu_ai_act.md).",
)


class TransparencyError(Exception):
    """A required transparency measure could not be applied; the output must not be released."""


@dataclass(frozen=True)
class Measure:
    code: str
    legal_ref: str
    description: str


def required_measures(p: AISystemProfile) -> List[Measure]:
    out: List[Measure] = []
    if p.interacts_with_natural_persons and not p.interaction_obvious_to_reasonable_person:
        out.append(Measure("interaction_disclosure", "AI Act Art. 50(1)", "Inform people they are interacting with an AI system"))
    if p.generates_synthetic_content and not p.synthetic_content_only_assistive_editing:
        out.append(Measure("machine_readable_marking", "AI Act Art. 50(2)", "Mark synthetic output in a machine-readable, detectable format"))
    if p.emotion_recognition or p.biometric_categorisation:
        out.append(Measure("exposed_person_notice", "AI Act Art. 50(3)", "Inform exposed natural persons of the system's operation"))
    if p.deepfake_content:
        out.append(Measure("deepfake_visible_label", "AI Act Art. 50(4)", "Disclose that the content is artificially generated or manipulated"))
    if p.public_interest_text and p.generates_synthetic_content:
        out.append(Measure("public_interest_text_label", "AI Act Art. 50(4)", "Disclose AI-generated text published to inform the public on matters of public interest, unless human editorial responsibility applies"))
    return out


def interaction_disclosure(system_name: str, language: str = "en") -> str:
    texts = {
        "en": f"You are interacting with {system_name}, an AI system, not a human.",
        "nl": f"U communiceert met {system_name}, een AI-systeem en geen mens.",
        "de": f"Sie interagieren mit {system_name}, einem KI-System und keinem Menschen.",
        "fr": f"Vous interagissez avec {system_name}, un système d'IA et non un humain.",
    }
    return texts.get(language, texts["en"])


def visible_label(kind: str, language: str = "en") -> str:
    labels = {
        "en": {"deepfake": "This content has been artificially generated or manipulated (AI).", "text": "This text was generated by AI."},
        "nl": {"deepfake": "Deze inhoud is kunstmatig gegenereerd of gemanipuleerd (AI).", "text": "Deze tekst is door AI gegenereerd."},
    }
    table = labels.get(language, labels["en"])
    return table["deepfake" if kind == "deepfake" else "text"]


def _b64(b: bytes) -> str:
    return base64.urlsafe_b64encode(b).decode("ascii").rstrip("=")


def _unb64(s: str) -> bytes:
    return base64.urlsafe_b64decode(s + "=" * (-len(s) % 4))


@dataclass(frozen=True)
class Released:
    content: Any
    manifest: Optional[Dict[str, Any]]
    disclosures: Tuple[str, ...]
    visible_label: Optional[str]
    measures_applied: Tuple[str, ...]
    limitations: Tuple[str, ...] = LIMITATIONS


class TransparencyMarker:
    def __init__(self, key: Optional[bytes], *, clock=time.time) -> None:
        self._key = hmac.new(key, b"slai-transparency-v1", hashlib.sha256).digest() if key and len(key) >= 32 else None
        self._clock = clock

    # ---------------------------------------------------------------- manifest
    def _sign(self, body: Mapping[str, Any]) -> str:
        if self._key is None:
            raise TransparencyError("no signing key configured: cannot apply machine-readable marking")
        return hmac.new(self._key, json.dumps(body, sort_keys=True, separators=(",", ":")).encode(), hashlib.sha256).hexdigest()

    def manifest_for(self, data: bytes, *, system_id: str, model: str, kind: str, provider: str = "") -> Dict[str, Any]:
        body = {"v": MANIFEST_VERSION, "ai_generated": True, "kind": kind, "system_id": system_id, "model": model, "provider": provider,
                "created_at": int(self._clock()), "content_sha256": hashlib.sha256(data).hexdigest()}
        return {**body, "signature": self._sign(body)}

    def verify(self, data: bytes, manifest: Mapping[str, Any]) -> bool:
        try:
            body = {k: v for k, v in manifest.items() if k != "signature"}
            if body.get("v") != MANIFEST_VERSION or self._key is None:
                return False
            if not hmac.compare_digest(str(manifest.get("signature", "")), self._sign(body)):
                return False
            return hmac.compare_digest(body.get("content_sha256", ""), hashlib.sha256(data).hexdigest())
        except Exception:
            return False

    # ---------------------------------------------------------------- PNG embedding (real metadata)
    @staticmethod
    def _png_chunks(png: bytes):
        if not png.startswith(b"\x89PNG\r\n\x1a\n"):
            raise TransparencyError("not a PNG file")
        pos = 8
        while pos + 8 <= len(png):
            length, ctype = struct.unpack(">I4s", png[pos:pos + 8])
            yield ctype, png[pos + 8: pos + 8 + length], pos, pos + 12 + length
            pos += 12 + length

    def embed_png(self, png: bytes, manifest: Mapping[str, Any]) -> bytes:
        payload = PNG_KEYWORD.encode("latin-1") + b"\x00" + _b64(json.dumps(dict(manifest), sort_keys=True).encode()).encode("ascii")
        chunk = struct.pack(">I", len(payload)) + b"tEXt" + payload + struct.pack(">I", zlib.crc32(b"tEXt" + payload) & 0xFFFFFFFF)
        for ctype, _data, start, _end in self._png_chunks(png):
            if ctype == b"IEND":
                return png[:start] + chunk + png[start:]
        raise TransparencyError("PNG has no IEND chunk")

    def extract_png(self, png: bytes) -> Optional[Dict[str, Any]]:
        for ctype, data, _s, _e in self._png_chunks(png):
            if ctype == b"tEXt" and data.startswith(PNG_KEYWORD.encode("latin-1") + b"\x00"):
                return json.loads(_unb64(data.split(b"\x00", 1)[1].decode("ascii")))
        return None

    def png_content_hash_source(self, png: bytes) -> bytes:
        """The bytes a PNG manifest is bound to: the image with the provenance chunk removed."""
        out, last = [], 0
        for ctype, data, start, end in self._png_chunks(png):
            if ctype == b"tEXt" and data.startswith(PNG_KEYWORD.encode("latin-1") + b"\x00"):
                out.append(png[last:start]); last = end
        out.append(png[last:])
        return b"".join(out)

    # ---------------------------------------------------------------- fail-closed release
    def release(self, profile: AISystemProfile, content: Any, *, model: str, kind: str = "text", provider: str = "",
                language: str = "en") -> Released:
        measures = required_measures(profile)
        codes = {m.code for m in measures}
        disclosures: List[str] = []
        label: Optional[str] = None
        manifest: Optional[Dict[str, Any]] = None
        out = content
        if "interaction_disclosure" in codes:
            disclosures.append(interaction_disclosure(profile.name, language))
        if "deepfake_visible_label" in codes:
            label = visible_label("deepfake", language)
        elif "public_interest_text_label" in codes:
            label = visible_label("text", language)
        if "exposed_person_notice" in codes:
            disclosures.append(f"{profile.name} uses emotion recognition or biometric categorisation; you are being informed as required by Art. 50(3).")
        if "machine_readable_marking" in codes:
            if kind == "text":
                data = str(content).encode("utf-8")
            elif kind == "png":
                data = self.png_content_hash_source(content)
            elif isinstance(content, (bytes, bytearray)):
                data = bytes(content)
            else:
                raise TransparencyError(f"cannot mark content of kind {kind!r}")
            manifest = self.manifest_for(data, system_id=profile.system_id, model=model, kind=kind, provider=provider)
            if kind == "png":
                out = self.embed_png(content, manifest)
        return Released(out, manifest, tuple(disclosures), label, tuple(sorted(codes)))
