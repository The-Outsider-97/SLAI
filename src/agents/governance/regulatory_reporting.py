"""Compliance reports and the article-level traceability matrix.

The matrix rows live in ``configs/traceability.json`` (data, under change control).
A row's *reported* status is computed here, never copied from the row:

* a row can only be reported ``implemented_and_verified`` if every control it links
  to is VERIFIED by evidence in the store;
* otherwise the weaker of the declared implementation status and the control
  statuses wins; a FAILED control always wins.
"""

from __future__ import annotations

import json
import time

from pathlib import Path
from typing import Any, Dict, List, Mapping, Optional

from .compliance_engine import Assessment, ControlStatus

__all__ = ["RegulatoryReporter", "DISCLAIMER"]

DISCLAIMER = (
    "This report is generated by SLAI's internal tooling. It is not legal advice, a certification "
    "or a statement of full compliance. Mandatory controls without independent evidence are shown "
    "as such, and organisational duties remain with the controller/provider."
)

_DECLARED = ("implemented", "partial", "missing", "organisational", "deployment", "not_applicable")
_RANK = {
    ControlStatus.FAILED.value: 0,
    ControlStatus.MISSING.value: 1,
    "partial": 2,
    ControlStatus.DEPENDS_ON_ORGANISATION.value: 3,
    ControlStatus.DEPENDS_ON_DEPLOYMENT.value: 3,
    ControlStatus.UNVERIFIED.value: 4,
    ControlStatus.VERIFIED.value: 5,
}


class RegulatoryReporter:
    def __init__(self, matrix_path: Optional[Path] = None):
        self._path = matrix_path or Path(__file__).resolve().parent / "configs" / "traceability.json"

    def load_matrix(self) -> List[Dict[str, Any]]:
        with open(self._path, "r", encoding="utf-8") as fh:
            rows = json.load(fh)["rows"]
        for row in rows:
            if row.get("declared") not in _DECLARED:
                raise ValueError(f"traceability row {row.get('article')} has invalid 'declared' value")
        return rows

    def traceability(self, assessment: Assessment) -> List[Dict[str, Any]]:
        by_control = {r.control.control_id: r for r in assessment.results}
        out: List[Dict[str, Any]] = []
        for row in self.load_matrix():
            declared = row["declared"]
            linked = [by_control[c] for c in row.get("controls", []) if c in by_control]
            if declared == "not_applicable":
                status = ControlStatus.NOT_APPLICABLE.value
            elif declared == "organisational":
                status = ControlStatus.DEPENDS_ON_ORGANISATION.value
            elif declared == "deployment":
                status = ControlStatus.DEPENDS_ON_DEPLOYMENT.value
            elif declared == "missing":
                status = ControlStatus.MISSING.value
            else:
                candidates = ["partial"] if declared == "partial" else [ControlStatus.UNVERIFIED.value]
                candidates += [r.status.value for r in linked if r.status is not ControlStatus.NOT_APPLICABLE]
                if declared == "implemented" and linked and all(r.status is ControlStatus.VERIFIED for r in linked):
                    status = ControlStatus.VERIFIED.value
                else:
                    status = min(candidates, key=lambda s: _RANK.get(s, 4))
                    if status == ControlStatus.MISSING.value and declared == "implemented":
                        status = ControlStatus.UNVERIFIED.value  # code exists; evidence is what is missing
            out.append({**row, "reported_status": status})
        return out

    def report(self, assessment: Assessment) -> Dict[str, Any]:
        matrix = self.traceability(assessment)
        counts: Dict[str, int] = {}
        for row in matrix:
            counts[row["reported_status"]] = counts.get(row["reported_status"], 0) + 1
        return {
            "generated_at": assessment.generated_at,
            "deployment_profile": assessment.profile,
            "evidence_chain_intact": assessment.chain_ok,
            "control_status_counts": assessment.counts(),
            "traceability_status_counts": counts,
            "software_release_allowed": assessment.release_allowed(include_organisational=False),
            "deployment_release_allowed": assessment.release_allowed(include_organisational=True),
            "blocking_controls": [r.to_dict() for r in assessment.blocking(include_organisational=True)],
            "controls": [r.to_dict() for r in assessment.results],
            "traceability": matrix,
            "disclaimer": DISCLAIMER,
        }

    def to_markdown(self, report: Mapping[str, Any]) -> str:
        lines = [
            f"# SLAI regulatory status — profile `{report['deployment_profile']}`",
            "",
            f"> {DISCLAIMER}",
            "",
            f"- Evidence chain intact: **{report['evidence_chain_intact']}**",
            f"- Software release allowed: **{report['software_release_allowed']}**",
            f"- Deployment release allowed (incl. organisational duties): **{report['deployment_release_allowed']}**",
            "",
            "## Controls",
            "",
            "| Control | Category | Status | Findings |",
            "|---|---|---|---|",
        ]
        for c in report["controls"]:
            lines.append(f"| {c['control_id']} {c['title']} | {c['category']} | {c['status']} | {'; '.join(c['findings'])} |")
        lines += ["", "## Article-level traceability", "", "| Article | Requirement | Status | Components | Limitation |", "|---|---|---|---|---|"]
        for r in report["traceability"]:
            lines.append(
                f"| {r['article']} | {r['requirement']} | {r['reported_status']} | {', '.join(r.get('components', []))} | {r.get('limitation', '')} |"
            )
        return "\n".join(lines) + "\n"
