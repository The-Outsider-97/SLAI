"""Deterministic validated ZIP writer with atomic replacement semantics."""
import os  # noqa: F401  (kept importable: tests patch ``writer.os.link``/``writer.os.replace``)
import zlib
from io import BytesIO
from pathlib import Path
from zipfile import ZipFile, ZipInfo, ZIP_DEFLATED, ZIP_STORED
from ..common.atomic import write_bytes_atomic
from ..common.errors import ConflictError, ValidationError, ResourceLimitError
from ..common.helpers import canonical_json, digest, MAX_DOCUMENT_NODES
from .reader import (MIMES, PAYLOADS, _manifest, _validate_name, MAX_UNPACKED, MAX_MEMBERS,
                     MAX_RATIO, MAX_ARCHIVE_SIZE)

def _entry(name, raw, archive, compression):
    entry = ZipInfo(name, (1980, 1, 1, 0, 0, 0))
    # Raw DEFLATE is used by ZIP. Store unusually compressible content so our
    # own reader's anti-bomb ratio limit never rejects a valid generated file.
    if compression == ZIP_DEFLATED:
        compressor = zlib.compressobj(wbits=-15)
        compressed = compressor.compress(raw) + compressor.flush()
        if len(raw) > MAX_RATIO * max(1, len(compressed)):
            compression = ZIP_STORED
    entry.compress_type = compression
    entry.create_system = 3
    entry.external_attr = 0o100644 << 16
    archive.writestr(entry, raw)

def build_package(manifest: dict, document: dict, assets=None, *, textures=None) -> tuple[bytes, dict]:
    """Serialize and fully verify a package in memory.

    Returns ``(zip_bytes, final_manifest)``. The bytes are re-read with the
    same bounded reader a consumer would use, so a returned package is known
    to load; the exact verified bytes are what callers publish or hash.

    ``textures`` (SGEO only) maps image id -> encoded PNG/JPEG bytes for exactly the document's image registry.
    """
    from .reader import loads_package
    format_id = manifest.get("format_id") if isinstance(manifest, dict) else None
    if not isinstance(format_id, str) or format_id not in MIMES:
        raise ValidationError("unsupported document format")
    payload = PAYLOADS[format_id]
    # Externalize SGEO indexed meshes after validating the complete in-memory scene.
    from ..verification.invariants import validate_document
    from .scene_buffers import externalize_scene, validate_buffer_references
    pre_manifest = {**manifest, "parts": [{"path": payload, "size": 0, "sha256": "0" * 64}]}
    validate_document(pre_manifest, document)
    if format_id == "slai.sgeo":
        # SGEO geometry resources are exclusively owned by the validated
        # scene codec. Reject even an explicitly supplied empty asset map:
        # callers must not select or override content-addressed members.
        if assets is not None:
            raise ValidationError("SGEO assets must be generated by the scene codec")
        encoded_document, generated_assets = externalize_scene(document, textures)
        assets = generated_assets
        document = encoded_document
    elif textures:
        raise ValidationError("only SGEO documents embed textures")
    assets = {} if assets is None else assets
    if not isinstance(assets, dict):
        raise ValidationError("assets must be a path-to-bytes mapping")
    members = {payload: canonical_json(document, max_nodes=MAX_DOCUMENT_NODES)}
    for name, content in assets.items():
        if not isinstance(name, str):
            raise ValidationError("asset path must be a string")
        _validate_name(name)
        if name in (payload, "manifest.json", "mimetype") or not isinstance(content, bytes):
            raise ValidationError("invalid asset path or payload")
        members[name] = content
    if len(members) + 2 > MAX_MEMBERS or sum(map(len, members.values())) > MAX_UNPACKED:
        raise ResourceLimitError("package exceeds resource budget")
    final_manifest = {**manifest, "parts": [
        {"path": name, "size": len(raw), "sha256": digest(raw)}
        for name, raw in sorted(members.items())
    ]}
    _manifest(final_manifest)
    if format_id == "slai.sgeo":
        validate_buffer_references(document, assets)
    # The semantic document was fully validated above, and the exact bytes about
    # to be published are re-read and re-validated by loads_package() below, so
    # another full validation here (the dominant cost of a save) adds no safety.
    manifest_bytes = canonical_json(final_manifest)
    buffer = BytesIO()
    with ZipFile(buffer, "w", allowZip64=False) as archive:
        _entry("mimetype", MIMES[format_id], archive, ZIP_STORED)
        _entry("manifest.json", manifest_bytes, archive, ZIP_DEFLATED)
        for member, raw in sorted(members.items()):
            _entry(member, raw, archive, ZIP_DEFLATED)
    data = buffer.getvalue()
    if len(data) > MAX_ARCHIVE_SIZE:
        raise ResourceLimitError("compressed spatial package too large")
    loads_package(data)
    return data, final_manifest


def dumps_package(manifest: dict, document: dict, assets=None, *, textures=None) -> bytes:
    """Return a verified package as bytes (no file is touched)."""
    return build_package(manifest, document, assets, textures=textures)[0]


def write_package(path, manifest: dict, document: dict, assets=None, *, overwrite=False, textures=None) -> str:
    """Write a package; return its SHA-256 hex digest.

    Never writes to a caller's existing file unless explicitly permitted. The
    archive is built and verified by the same reader before any file is
    created, then published atomically (see :mod:`..common.atomic`).
    """
    if not overwrite and Path(path).exists():
        raise ConflictError("output file already exists", path=str(path))
    data, _ = build_package(manifest, document, assets, textures=textures)
    return write_bytes_atomic(path, data, overwrite=overwrite)


def write_document(path, document, *, overwrite=False):
    """Save one consistent model snapshot through the validated package writer."""
    from ..sgeo.scene import Scene
    from ..sdrw.drawing import Drawing
    if not isinstance(document, (Scene, Drawing)):
        raise ValidationError("expected a Scene or Drawing")
    with document._mutation_lock:
        manifest = document.manifest()
        payload = document.as_dict()
        textures = dict(document.image_data) if isinstance(document, Scene) else None
    return write_package(path, manifest, payload, overwrite=overwrite, textures=textures)
