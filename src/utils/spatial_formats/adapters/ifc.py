"""Optional IfcOpenShell BIM extraction, with explicit semantic fidelity boundaries.

Imports selected IfcProduct objects and Ifc spatial containment to SGEO scenes.
Geometry is generated by IfcOpenShell's native geometry engine, not by custom
IFC parsing. IFC GlobalIds remain attributable metadata; they are not UUIDs.
Unsupported geometry and absent geometry engines fail, never fabricate solids.
"""
from __future__ import annotations
from pathlib import Path
from ..common.errors import DependencyUnavailableError, UnsupportedFeatureError, ResourceLimitError, ValidationError
from ..common.ids import new_id
from ..sgeo.scene import Scene
from .contracts import Capabilities
_ALLOWED=frozenset(("IfcWall","IfcWallStandardCase","IfcSlab","IfcRoof","IfcDoor","IfcWindow",
                    "IfcColumn","IfcBeam","IfcMember","IfcPlate","IfcFooting","IfcStair",
                    "IfcRailing","IfcSpace","IfcBuildingElementProxy"))
_SCHEMAS=("IFC2X3","IFC4","IFC4X3")
_MAX_SIZE=64*1024*1024

def _ifc_backend():
    try:
        import ifcopenshell
        import ifcopenshell.geom
    except ImportError as exc:
        raise DependencyUnavailableError("IFC import requires compatible IfcOpenShell and its geometry engine") from exc
    return ifcopenshell

def capabilities():
    try: _ifc_backend();available=True
    except DependencyUnavailableError: available=False
    return Capabilities("ifc","ifcopenshell",available,_SCHEMAS if available else (),(),
                        tuple(sorted(_ALLOWED)),("IFC export is not supported",
                        "Triangulated geometry only; original B-rep is not preserved",
                        "Property sets, materials and georeferencing are not round-tripped"))

def import_ifc(path, *, max_products=10000, strict=True):
    backend=_ifc_backend()
    source=Path(path)
    if not source.is_file() or source.is_symlink() or not 0<source.stat().st_size<=_MAX_SIZE:
        raise ResourceLimitError("invalid or oversized IFC file")
    model=backend.open(str(source))
    schema=str(model.schema).upper()
    if schema not in _SCHEMAS:
        raise UnsupportedFeatureError("unsupported IFC schema: "+schema)
    products=model.by_type("IfcProduct")
    if len(products)>max_products or max_products>10000:
        raise ResourceLimitError("IFC product budget exceeded")
    scene=Scene(name="IFC import",unit="m")
    settings=backend.geom.settings()
    settings.set(settings.USE_WORLD_COORDS,True)
    for product in products:
        if not product.is_a() in _ALLOWED:
            # Spatial containers without geometry are not represented by this
            # bounded geometry-first import profile.
            if product.Representation is not None and strict:
                raise UnsupportedFeatureError("unsupported IFC product class "+product.is_a())
            continue
        if product.Representation is None:
            if strict: raise UnsupportedFeatureError("IFC product has no geometric representation")
            continue
        try:
            shape=backend.geom.create_shape(settings,product)
            verts=list(shape.geometry.verts)
            faces=list(shape.geometry.faces)
        except Exception as exc:
            raise UnsupportedFeatureError("IFC geometry engine failed to tessellate product") from exc
        if len(verts)%3 or len(faces)%3 or len(verts)>3_000_000 or len(faces)>6_000_000:
            raise ResourceLimitError("invalid IFC geometry buffer")
        geometry={"kind":"mesh","vertices":[verts[i:i+3] for i in range(0,len(verts),3)],
                  "faces":[faces[i:i+3] for i in range(0,len(faces),3)]}
        if not geometry["faces"]:
            if strict: raise UnsupportedFeatureError("IFC product has no triangles")
            continue
        scene.add_object(name=str(product.Name or product.is_a())[:255],geometry=geometry,
                         metadata={"ifc:global_id":str(product.GlobalId),
                                   "ifc:entity":str(product.is_a()),
                                   "ifc:express_id":int(product.id())})
    return scene

