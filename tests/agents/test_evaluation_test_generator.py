def test_prepare_requires_verified_provenance_and_split_groups(tmp_path):
    rows = []
    for index in range(10):
        rows.append({
            "source": SOURCE + f"# Case {index}\n",
            "test": VALID + f"\n# Variant {index}\n",
            "verified": True, "synthetic": True,
            "license": "synthetic-smoke-only",
            "provenance": f"synthetic-fixture-{index}",
            "group": f"example-group-{index // 2}",
            "target_symbol": "increment",
            "target_module": "example",
        })
    raw = tmp_path / "cases.jsonl"
    raw.write_text("\n".join(json.dumps(row) for row in rows) + "\n", encoding="utf-8")
    prepared = tmp_path / "prepared"
    summary = prepare_dataset(raw, prepared)
    assert summary["schema"] == SCHEMA
    assert sum(summary["counts"].values()) == 10
    assert summary["synthetic_count"] == 10
    seen = []
    for split in ("train", "validation", "test"):
        data = [json.loads(s) for s in (prepared / f"{split}.jsonl").read_text(encoding="utf-8").splitlines()]
        assert data
        seen.append({r["group"] for r in data})
    assert all(not a & b for idx, a in enumerate(seen) for b in seen[idx + 1:])


def test_unverified_rows_do_not_become_training_examples(tmp_path):
    f = tmp_path / "unverified.jsonl"
    f.write_text(json.dumps({
        "source": SOURCE, "test": VALID, "verified": False, "group": "a",
        "license": "test", "provenance": "unverified", "target_symbol": "increment",
    }) + "\n", encoding="utf-8")
    with pytest.raises(ValueError, match="verified"):
        prepare_dataset(f, tmp_path / "prepared")


def test_training_save_and_load_is_explicit_and_unapproved(tmp_path):
    torch = pytest.importorskip("torch")
    raw = tmp_path / "source.jsonl"
    rows = [
        {
            "source": SOURCE + f"# {i}\n", "test": VALID + f"\n# {i}\n",
            "verified": True, "synthetic": True,
            "license": "synthetic-smoke-only", "provenance": f"fixture-{i}",
            "group": f"group-{i}", "target_symbol": "increment",
            "target_module": "example",
        }
        for i in range(10)
    ]
    raw.write_text("\n".join(json.dumps(r) for r in rows) + "\n", encoding="utf-8")
    prepared = tmp_path / "prepared"
    prepare_dataset(raw, prepared)
    checkpoint = tmp_path / "checkpoint"
    manifest = train_model(
        prepared, checkpoint, epochs=1, seed=42,
        embed_dim=8, hidden_dim=16, max_source_bytes=32, max_target_bytes=64,
    )
    assert manifest["promotion"] == "experimental"
    assert (checkpoint / "weights.pt").is_file()
    model = TestGenerator(checkpoint_dir=checkpoint, mode="advisory")
    result = model.generate({"source": SOURCE, "target_symbol": "increment"})
    assert result["status"] == "checkpoint_not_approved"
    assert model.health()["loaded"] is True
    # Tampering must prevent a fresh instance from loading weights.
    (checkpoint / "weights.pt").write_bytes(b"tampered")
    tampered = TestGenerator(checkpoint_dir=checkpoint, mode="shadow")
    assert tampered.generate({"source": SOURCE, "target_symbol": "increment"})["status"] == "unavailable"


def test_evaluator_config_isolation_and_deleted_file_fail_closed(tmp_path):
    from src.agents.evaluators.utils import config_loader as loader
    config_path = tmp_path / "evaluator.yml"
    config_path.write_text("nested:\n  threshold: 5\n", encoding="utf-8")
    try:
        first = loader.load_global_config(config_path, force_reload=True)
        first["nested"]["threshold"] = 999
        second = loader.load_global_config(config_path)
        assert second["nested"]["threshold"] == 5
        section = loader.get_config_section("nested", config=second)
        section["threshold"] = -99
        assert loader.get_config_section("nested", config=second)["threshold"] == 5
        config_path.unlink()
        with pytest.raises(FileNotFoundError):
            loader.load_global_config(config_path, cache_ttl=600)
    finally:
        loader.clear_config_cache()


def test_evaluation_agent_generates_only_when_explicitly_enabled():
    from src.agents.evaluation_agent import EvaluationAgent
    # Exercise the real facade dispatch without initializing unrelated evaluators.
    facade = EvaluationAgent.__new__(EvaluationAgent)
    facade.agent_config = {"test_generator": {"mode": "disabled"}}
    facade._test_generator_lock = threading.RLock()
    facade._test_generator = None
    response = facade.predict({
        "operation": "generate_tests", "source": SOURCE,
        "target_symbol": "increment", "framework": "pytest",
    })
    assert response["status"] == "disabled"
    assert response["execution"] == "not_executed"
